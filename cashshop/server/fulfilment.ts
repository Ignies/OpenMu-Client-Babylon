/**
 * The gate's refusal, in the words the delivery tab shows. The signal names
 * and their technical reasons go to the audit log; the player gets told what
 * to do about it.
 */
function playerWords(verdict: GateVerdict): string {
  const refused = verdict.signals.filter(signal => !signal.safe);
  const named = (name: SignalResult['name']) => refused.find(signal => signal.name === name);

  const presence = named('presence');
  if (presence) {
    if (/logged in/.test(presence.reason)) {
      return 'You are logged in. Log out and it will be delivered within a minute.';
    }
    if (/logged out/.test(presence.reason)) {
      return 'You logged out a moment ago. It will be delivered within a minute.';
    }
    return 'The shop cannot see who is online right now. It will keep trying.';
  }

  if (named('writeRecency')) {
    return (
      'Your characters were saved a moment ago, so you may still be playing. ' +
      'It will be delivered once the game has been quiet for a few minutes.'
    );
  }

  if (named('personalStore')) {
    return 'A character on your account has a personal store open. Close it and log out.';
  }

  return 'Deliveries are paused while the server is checked. Your order keeps its place.';
}

function describe(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/** The audit's view of a verdict: every signal, safe or not. */
function signalsOf(verdict: GateVerdict): Record<string, { safe: boolean; reason: string }> {
  const out: Record<string, { safe: boolean; reason: string }> = {};
  for (const signal of verdict.signals) out[signal.name] = { safe: signal.safe, reason: signal.reason };
  return out;
}

/* ------------------------------------------------------------------ worker */

/**
 * The delivery worker. One per process, sharing the one `SafetyGate`: the
 * gate's sampling fallback and probe cache live on the instance, and a fresh
 * gate per order would refuse forever on a database without commit
 * timestamps.
 *
 * One account at a time, and all of an account's queued orders in one pass
 * under one gate verdict and one State lock. That is not only faster: the
 * write-recency signal reads `data."Item"`, so the shop's own commit looks
 * like a save for the next three minutes, and delivering twelve gacha rolls
 * one pass apiece would take the better part of an hour.
 */
export class Fulfilment {
  private resolved: Resolved | null = null;
  private timer: ReturnType<typeof setTimeout> | null = null;
  private sweeper: ReturnType<typeof setInterval> | null = null;
  private running = false;
  private stopped = false;
  /** Accounts whose `State` this process holds locked right now, by id, for the sweep. */
  private readonly inFlight = new Set<string>();
  /**
   * `group/number` -> whether the game configuration defines it. Definitions
   * do not change while the server runs.
   */
  private readonly grantableByKey = new Map<string, boolean>();

  constructor(
    private readonly sql: Sql,
    private readonly gate: SafetyGate,
    private readonly config: FulfilmentConfig = loadFulfilmentConfig()
  ) {}

  get mode(): 'on' | 'off' {
    return this.config.fulfil ? 'on' : 'off';
  }

  /** Whether the service can honestly tell the window it will deliver. */
  get acceptingOrders(): boolean {
    return this.resolved !== null;
  }

  /**
   * Resolves the schema and the configuration once, so a database that does
   * not look as expected is refused at boot, loudly, and not on the first
   * order. Retried on every poll until it succeeds, because the database may
   * simply not be up yet. The schema is the gate's own resolution: one walk
   * of `information_schema` per process, and no way for the two to disagree.
   */
  async resolveOnce(): Promise<Resolved> {
    if (this.resolved) return this.resolved;

    const schema = await this.gate.schemaOnce();
    const gameConfigurationId = await resolveGameConfiguration(this.sql, schema);
    const excellentTypeId = await resolveExcellentType(this.sql, schema);
    const partial = { schema, gameConfigurationId, excellentTypeId, chaosDefinitionId: '' };
    const chaos = await findDefinition(this.sql, partial, JEWEL_OF_CHAOS.group, JEWEL_OF_CHAOS.num);

    if (!chaos) {
      throw new Error(
        'the game configuration has no Jewel of Chaos ' +
          `(${JEWEL_OF_CHAOS.group}/${JEWEL_OF_CHAOS.num}) definition`
      );
    }

    this.resolved = { ...partial, chaosDefinitionId: chaos.id };
    console.info(
      `cash shop fulfilment ${this.mode}: schema resolved, ` +
        `game configuration ${gameConfigurationId}, chaos definition ${chaos.id}`
    );

    return this.resolved;
  }

  /**
   * Whether the running game configuration defines this item at all, so a
   * gacha roll can be checked before it is committed rather than failing the
   * player at delivery with an item the game cannot hand over. Null when the
   * database cannot be asked, which the caller must treat as "do not roll".
   */
  async grantable(group: number, number: number): Promise<boolean | null> {
    const key = `${group}/${number}`;
    const known = this.grantableByKey.get(key);

    if (known !== undefined) return known;

    try {
      const resolved = await this.resolveOnce();
      const found = (await findDefinition(this.sql, resolved, group, number)) !== null;

      this.grantableByKey.set(key, found);

      return found;
    } catch (error) {
      console.error(`definition lookup for ${key} failed:`, describe(error));
      return null;
    }
  }

  /**
   * The wallet as the database has it: the delivery character's bag plus the
   * vault (`deliveryCharacter` says why that character and no other), which
   * is the placement route's bound. Null when the account is unknown or the
   * schema is not resolved yet, which the route should treat as "cannot
   * accept orders", never as zero.
   */
  async wallet(loginName: string): Promise<{ chaos: number } | null> {
    try {
      const resolved = await this.resolveOnce();
      const account = await this.gate.findAccount(loginName);

      if (!account) return null;

      const character = await deliveryCharacter(this.sql, resolved, account.id);
      const jewels = await chaosRows(
        this.sql,
        resolved,
        character?.inventoryId ?? null,
        account.vaultId,
        false
      );

      return { chaos: jewels.length };
    } catch (error) {
      console.error(`wallet read for ${loginName} failed:`, error);
      return null;
    }
  }

  start(): void {
    if (this.timer || this.sweeper) return;
    this.stopped = false;

    console.info(
      `cash shop fulfilment is ${this.mode}` +
        (this.config.fulfil
          ? ''
          : ' (rehearsing: nothing will be written; set CASHSHOP_FULFIL=on)')
    );

    this.reportInterrupted();
    void this.sweep();
    this.sweeper = setInterval(() => void this.sweep(), this.config.sweepMs);
    this.sweeper.unref();
    this.schedule(0);
  }

  /**
   * Orders a previous process claimed and never settled. A claim and its
   * settlement happen in one pass, so anything still `delivering` at boot
   * was cut off - by a deploy's restart, most likely - and whether its
   * transaction committed is a fact only OpenMU's database holds. Requeueing
   * would deliver twice if it did; failing would tell the player nothing was
   * spent if it was. So they are named, loudly, and left for a person and
   * `cashshop-orders`.
   */
  private reportInterrupted(): void {
    const interrupted = deliveringOrders();

    if (interrupted.length === 0) return;

    for (const order of interrupted) {
      explainDelivering(order.id, 'Delivery was interrupted. Someone will check it.');
      audit('found delivering at boot', { account: order.account, orderId: order.id });
    }

    console.error(
      `${interrupted.length} order(s) were left delivering by a previous run ` +
        'and need a person to settle them (bun run cashshop-orders): ' +
        interrupted.map(order => `${order.id} for ${order.account}`).join(', ')
    );
  }

  stop(): void {
    this.stopped = true;
    if (this.timer) clearTimeout(this.timer);
    if (this.sweeper) clearInterval(this.sweeper);
    this.timer = null;
    this.sweeper = null;
  }

  private schedule(delay: number): void {
    if (this.stopped) return;
    this.timer = setTimeout(() => void this.tick(), delay);
    this.timer.unref();
  }

  /** One look at the queue. Never overlaps itself: a slow gate check must not stack. */
  async tick(): Promise<void> {
    if (this.running) return;
    this.running = true;

    try {
      const byAccount = new Map<string, QueuedOrder[]>();

      for (const order of queuedOrders()) {
        byAccount.set(order.account, [...(byAccount.get(order.account) ?? []), order]);
      }

      if (byAccount.size > 0) await this.resolveOnce();

      for (const [account, orders] of byAccount) {
        if (this.stopped) break;
        await this.deliverAccount(account, orders);
      }
    } catch (error) {
      console.error('fulfilment pass failed:', describe(error));
    } finally {
      this.running = false;
      this.schedule(this.config.pollMs);
    }
  }

  /**
   * Steps 1 to 5 and 14 to 15 for one account, with every one of its queued
   * orders run through steps 6 to 13 in between, oldest first.
   */
  private async deliverAccount(loginName: string, orders: QueuedOrder[]): Promise<void> {
    const resolved = await this.resolveOnce();
    const first = await this.gate.check(loginName);

    if (!first.safe) {
      this.defer(loginName, orders, first, 'delivery deferred');
      return;
    }

    const account = await this.gate.findAccount(loginName);

    if (!account) {
      const words = 'The shop cannot find your account right now. It will keep trying.';
      for (const order of orders) this.wait(order, words);
      return;
    }

    if (account.state !== ACCOUNT_NORMAL) {
      // A GM, a spectator or a banned account is refused outright: the lock
      // below rewrites State, and the shop must never be able to unban.
      const words = 'Your account is not in a state the shop can deliver to.';
      for (const order of orders) this.wait(order, words);
      audit('delivery refused', {
        account: loginName,
        detail: { state: account.state, orders: orders.map(order => order.id) },
      });
      return;
    }

    const locked = this.config.fulfil ? await this.lock(account) : true;

    if (!locked) {
      const words = 'Your account changed while the shop was checking it. It will try again.';
      for (const order of orders) this.wait(order, words);
      return;
    }

    let pass: { verdict: GateVerdict; committed: number } | null;

    try {
      pass = await this.deliverLocked(resolved, account, loginName, orders);
    } finally {
      if (this.config.fulfil) await this.unlock(account);
    }

    if (!pass) return;

    // Step 15: the same three questions again. The write-recency signal is
    // expected to have flipped - the commits above are writes to this
    // account's items - so it is recorded rather than flagged; presence and
    // the store flag changing is what would mean a session slipped through.
    const after = await this.gate.check(loginName);
    const flipped = after.signals
      .filter(signal => signal.name === 'presence' || signal.name === 'personalStore')
      .filter(signal => !signal.safe);

    audit(flipped.length ? 'post-commit anomaly' : 'post-commit check', {
      account: loginName,
      detail: { committed: pass.committed, before: signalsOf(pass.verdict), after: signalsOf(after) },
    });

    if (flipped.length) {
      console.error(
        `post-commit anomaly for ${loginName}: ` +
          flipped.map(signal => `${signal.name}: ${signal.reason}`).join('; ')
      );
    }
  }

  /**
   * Steps 6 to 13 for each order, behind the reading that counts. The check
   * before the lock bought a cheap refusal and nothing more: its presence
   * answer was taken seconds before `State` changed, and a login whose frame
   * passed the proxy in between is loaded by OpenMU with `State` still
   * Normal, which the lock does not undo. Now that no login can start, every
   * session that did start is one the proxy already knows about, one way or
   * the other: a login OpenMU has answered is named (the proxy names a socket
   * off the server's Okay, and reads it in the same handler that forwards
   * it), and one it has accepted but not yet answered is still a pending
   * claim, which the proxy counts as unidentified and the gate refuses for
   * everyone. So a second reading is authoritative. It fails closed like the
   * first, and the whole pass waits for the next poll.
   */
  private async deliverLocked(
    resolved: Resolved,
    account: AccountRow,
    loginName: string,
    orders: QueuedOrder[]
  ): Promise<{ verdict: GateVerdict; committed: number } | null> {
    const verdict = await this.gate.check(loginName);

    if (!verdict.safe) {
      this.defer(loginName, orders, verdict, 'delivery deferred after lock');
      return null;
    }

    let committed = 0;

    for (const order of orders) {
      if (this.stopped) break;
      if (await this.deliverOrder(resolved, account, order, verdict)) committed++;
    }

    return { verdict, committed };
  }

  /** Every order of the pass told the gate's words, and the whole verdict on one audit row. */
  private defer(loginName: string, orders: QueuedOrder[], verdict: GateVerdict, event: string): void {
    const words = playerWords(verdict);

    for (const order of orders) this.wait(order, words);

    audit(event, {
      account: loginName,
      detail: {
        orders: orders.map(order => order.id),
        refusals: verdict.refusals,
        signals: signalsOf(verdict),
      },
    });
  }

  /**
   * Step 5: journal, then lock. The journal comes first so a crash between
   * the two leaves a record, not a mystery.
   */
  private async lock(account: AccountRow): Promise<boolean> {
    const { account: a } = (await this.resolveOnce()).schema;

    journalLock(account.id, account.state);

    const result = await this.sql.unsafe(
      `UPDATE ${a.ref} SET ${a.col.state} = $1 WHERE ${a.col.id} = $2 AND ${a.col.state} = $3`,
      [ACCOUNT_TEMPORARILY_BANNED, account.id, ACCOUNT_NORMAL]
    );

    if (result.count !== 1) {
      clearLock(account.id);
      return false;
    }

    this.inFlight.add(account.id);

    return true;
  }

  /**
   * Step 14: restore, whatever happened, then clear the journal. Only a row
   * still holding the lock's value is touched.
   */
  private async unlock(account: AccountRow): Promise<void> {
    try {
      const { account: a } = (await this.resolveOnce()).schema;

      await this.sql.unsafe(
        `UPDATE ${a.ref} SET ${a.col.state} = $1 WHERE ${a.col.id} = $2 AND ${a.col.state} = $3`,
        [account.state, account.id, ACCOUNT_TEMPORARILY_BANNED]
      );
      clearLock(account.id);
    } catch (error) {
      // The journal entry stays, and the sweep restores it within the minute.
      console.error(
        `could not restore State for ${account.loginName}; the sweep will:`,
        describe(error)
      );
    } finally {
      this.inFlight.delete(account.id);
    }
  }

  /**
   * One order, claimed and settled. True when a row was committed. The claim
   * is conditional on the order still being queued, so a cancel that landed
   * between the poll and now wins and the order is skipped.
   */
  private async deliverOrder(
    resolved: Resolved,
    account: AccountRow,
    queued: QueuedOrder,
    verdict: GateVerdict
  ): Promise<boolean> {
    const order = claimForDelivery(queued.id);

    if (!order) return false;

    const rehearse = !this.config.fulfil;
    let delivery: Delivery;

    try {
      // Anything thrown by the callback itself is thrown before COMMIT was
      // sent, and Postgres rolls back: nothing was written and the order can
      // safely go back to the queue. Anything that escapes `begin` without
      // that wrapper came from the machinery around the callback - the COMMIT
      // itself, or a connection that dropped after it was sent - and whether
      // the write landed is unknowable from here.
      delivery = await this.sql.begin(async tx => {
        try {
          return await deliverInTransaction(tx, resolved, account, order, rehearse);
        } catch (inner) {
          throw new BeforeCommit(inner);
        }
      });
    } catch (thrown) {
      const error = thrown instanceof BeforeCommit ? thrown.inner : thrown;

      if (!(thrown instanceof BeforeCommit)) {
        // The one outcome this must never turn into a retry: a delivery that
        // did commit would be delivered again, and the jewels taken twice.
        // The order stays `delivering`, the player is told, the audit row
        // carries the error, and `cashshop-orders` is how a person decides.
        explainDelivering(
          order.id,
          'The shop could not tell whether this was delivered. Someone will check it.'
        );
        audit('delivery outcome unknown', {
          account: account.loginName,
          orderId: order.id,
          detail: { error: describe(error), signals: signalsOf(verdict) },
        });
        console.error(
          `order ${order.id} for ${account.loginName}: ` +
            'COMMIT outcome unknown, left as delivering for review:',
          error
        );
        return false;
      }

      if (error instanceof Rehearsed) {
        const { delivery } = error;
        const where = delivery.spent.map(jewel => `${jewel.storage}:${jewel.slot}`).join(', ');

        settle(order.id, 'queued', REHEARSAL_WORDS);
        audit('rehearsed', {
          account: account.loginName,
          orderId: order.id,
          detail: this.auditDetail(order, delivery, verdict),
        });
        console.info(
          `rehearsed order ${order.id} for ${account.loginName}/${delivery.character}: ` +
            `would DELETE ${delivery.spent.length} chaos (${where}) ` +
            `and INSERT ${this.describeGrant(order, delivery)} at slot ${delivery.slot}`
        );
        return false;
      }

      if (error instanceof Refusal) {
        settle(order.id, error.outcome, error.message);
        audit(`delivery ${error.outcome === 'failed' ? 'failed' : 'deferred'}`, {
          account: account.loginName,
          orderId: order.id,
          detail: { reason: error.message, signals: signalsOf(verdict) },
        });
        console.info(`order ${order.id} for ${account.loginName} ${error.outcome}: ${error.message}`);
        return false;
      }

      // Anything else is the database, not the player, and it happened
      // before COMMIT: the order keeps its place, the operator gets the real
      // error, the player gets a sentence.
      settle(order.id, 'queued', 'The shop hit a problem delivering this. It will try again.');
      audit('delivery error', {
        account: account.loginName,
        orderId: order.id,
        detail: { error: describe(error), signals: signalsOf(verdict) },
      });
      console.error(`order ${order.id} for ${account.loginName} errored:`, error);
      return false;
    }

    // Committed. From here on nothing may send the order back to the queue:
    // the item is in the bag and the jewels are gone. A bookkeeping failure
    // leaves it `delivering`, which the boot check and the CLI surface, and
    // is the right side to err on.
    try {
      settle(order.id, 'delivered', `Delivered to ${delivery.character}'s bag.`, delivery.itemId);
      audit('delivered', {
        account: account.loginName,
        orderId: order.id,
        detail: this.auditDetail(order, delivery, verdict),
      });
      console.info(
        `delivered order ${order.id} to ${account.loginName}/${delivery.character}: ` +
          `${this.describeGrant(order, delivery)} at slot ${delivery.slot} ` +
          `for ${delivery.spent.length} chaos`
      );
    } catch (error) {
      console.error(
        `order ${order.id} for ${account.loginName} was delivered (item ${delivery.itemId}) ` +
          'but could not be recorded; it stays delivering for review:',
        error
      );
    }

    return true;
  }

  private describeGrant(order: Order, delivery: Delivery): string {
    const { grant } = delivery;
    const options = grant.optionIds.length ? ` with ${grant.optionIds.length} excellent option(s)` : '';
    const roll = order.roll ? ` [${describeRoll(order.roll)}]` : '';

    return `${grant.definitionName} +${grant.level} (${grant.width}x${grant.height})${options}${roll}`;
  }

  /**
   * Everything ARCHITECTURE.md asks an audit row to name: account, character,
   * product, jewels, item, seed, gate readings.
   */
  private auditDetail(order: Order, delivery: Delivery, verdict: GateVerdict): Record<string, unknown> {
    return {
      productId: order.productId,
      productName: order.productName,
      line: order.line,
      character: delivery.character,
      slot: delivery.slot,
      chaos: order.chaos,
      walletBefore: delivery.walletBefore,
      spent: delivery.spent.map(jewel => ({ id: jewel.id, storage: jewel.storage, slot: jewel.slot })),
      itemId: delivery.itemId,
      definitionId: delivery.grant.definitionId,
      definitionName: delivery.grant.definitionName,
      level: delivery.grant.level,
      optionIds: delivery.grant.optionIds,
      seed: delivery.grant.seed,
      roll: order.roll,
      signals: signalsOf(verdict),
    };
  }

  /**
   * A queued order told why it is waiting. Claimed and handed straight back so
   * the reason lands on the row; only when the reason changed, because every
   * settle is an audit row and a player who stays online is polled all night.
   */
  private wait(order: QueuedOrder, reason: string): void {
    if (order.reason === reason) return;
    if (claimForDelivery(order.id)) settle(order.id, 'queued', reason);
  }

  /**
   * Restores `State` on any account a dead process left locked. Runs at boot
   * and every `sweepMs`, so a SIGKILL mid-transaction costs a player about a
   * minute of "temporarily blocked" and never a permanent lockout. Only a row
   * still holding the lock's value is touched: an operator who changed the
   * state meanwhile is not overruled.
   *
   * A lock this process holds is left alone whatever its age. The journal
   * row's age cannot tell a dead holder from a slow one: a pass delivers all
   * of an account's orders under one lock, and twelve gacha rolls behind a
   * stalled Postgres can honestly outlive `LOCK_STALE_MS`. Restoring `State`
   * under such a pass would reopen login for the rest of it - the very race
   * the lock exists to close - so `inFlight` is consulted first. A process
   * that died has no set to consult, which is the case the sweep is for.
   */
  async sweep(): Promise<void> {
    const stale = staleLocks().filter(lock => !this.inFlight.has(lock.accountId));

    if (stale.length === 0) return;

    let schema: ResolvedSchema;

    try {
      schema = (await this.resolveOnce()).schema;
    } catch (error) {
      console.error(`${stale.length} stale account lock(s) cannot be restored yet:`, describe(error));
      return;
    }

    const { account: a } = schema;

    for (const lock of stale) {
      const age = Math.round((Date.now() - lock.lockedAt) / 1000);

      try {
        const result = await this.sql.unsafe(
          `UPDATE ${a.ref} SET ${a.col.state} = $1 WHERE ${a.col.id} = $2 AND ${a.col.state} = $3`,
          [lock.originalState, lock.accountId, ACCOUNT_TEMPORARILY_BANNED]
        );
        clearLock(lock.accountId);
        audit('stale lock restored', {
          detail: { accountId: lock.accountId, lockedAt: lock.lockedAt, restored: result.count === 1 },
        });
        console.warn(
          `restored State on account ${lock.accountId} locked ${age}s ago` +
            (result.count === 1 ? '' : ' (it was no longer locked)')
        );
      } catch (error) {
        console.error(`could not restore State on account ${lock.accountId}:`, describe(error));
      }
    }
  }
}
