interface CharacterRow {
  id: string;
  name: string;
  inventoryId: string;
  slot: number;
  inventoryExtensions: number;
}

/** What one delivery resolved before it touched anything, for the audit row. */
interface Grant {
  definitionId: string;
  definitionName: string;
  level: number;
  width: number;
  height: number;
  durability: number;
  /** `IncreasableItemOption` ids, in option-number order. */
  optionIds: string[];
  seed: number | null;
}

interface Delivery {
  character: string;
  slot: number;
  spent: JewelRow[];
  walletBefore: number;
  grant: Grant;
  itemId: string | null;
}

/**
 * A refusal the player will read. `queued` means try again next time - the
 * order keeps its place - and `failed` means the order is over and nothing
 * was spent. Every path through the transaction that is not a commit ends in
 * one of these, in words rather than a stack trace.
 */
class Refusal extends Error {
  constructor(
    message: string,
    readonly outcome: 'queued' | 'failed'
  ) {
    super(message);
  }
}

/**
 * Wraps whatever the transaction callback threw, so the caller can tell
 * "before COMMIT" from "around it".
 */
class BeforeCommit extends Error {
  constructor(readonly inner: unknown) {
    super('before commit');
  }
}

/** Thrown at the end of a rehearsal so the transaction rolls back with its reads done. */
class Rehearsed extends Error {
  constructor(readonly delivery: Delivery) {
    super('rehearsal');
  }
}

/** The order's product, or the grant a fixed product resolves to on the catalogue. */
function productOf(order: Order): Product {
  const product = productById(order.productId);

  if (!product) {
    throw new Refusal(
      `The shop no longer sells "${order.productName}". Nothing was spent.`,
      'failed'
    );
  }

  return product;
}

/**
 * What to insert. A fixed product is its catalogue entry at its level; a
 * gacha order is its stored roll, granted exactly - the seed is in the audit
 * row so the item can be checked against `roll(seed)` later. Both are checked
 * against the game's own definition: the footprint the shop fitted must be the
 * footprint the game will draw, and the level must be one the definition
 * allows.
 */
async function resolveGrant(tx: TransactionSql, resolved: Resolved, order: Order): Promise<Grant> {
  const product = productOf(order);
  let group: number;
  let number: number;
  let level: number;
  let width: number;
  let height: number;
  let labels: string[] = [];
  let seed: number | null = null;

  if (order.line === 'gacha') {
    const roll: Roll | null = order.roll;

    if (!roll) {
      throw new Refusal(
        'This roll was never recorded, so it cannot be delivered. Nothing was spent.',
        'failed'
      );
    }

    ({ group, num: number, level, width, height, seed } = roll);
    labels = roll.excellent ? roll.options : [];
  } else {
    if (product.group === null || product.number === null) {
      throw new Refusal(`"${product.name}" is not an item the shop can place in a bag.`, 'failed');
    }

    ({ group, number, level, width, height } = product);
  }

  const definition = await findDefinition(tx, resolved, group, number);

  if (!definition) {
    throw new Refusal(
      `The game has no item ${group}/${number} to give you. Nothing was spent.`,
      'failed'
    );
  }

  if (definition.width !== width || definition.height !== height) {
    throw new Refusal(
      `The game says "${definition.name}" is ${definition.width}x${definition.height}, ` +
        `the shop thought ${width}x${height}. Nothing was spent.`,
      'failed'
    );
  }

  if (level > definition.maximumLevel) {
    throw new Refusal(
      `"${definition.name}" cannot be +${level}; ` +
        `the game allows up to +${definition.maximumLevel}. Nothing was spent.`,
      'failed'
    );
  }

  const optionIds: string[] = [];

  if (labels.length > 0) {
    const available = await excellentOptionsOf(tx, resolved, definition.id);
    const numbers = [...new Set(labels.map(excellentNumberOf))].sort((a, b) => a - b);

    for (const n of numbers) {
      const id = available.get(n);

      if (!id) {
        throw new Refusal(
          `"${definition.name}" cannot carry excellent option ${n} in this game. ` +
            'Nothing was spent.',
          'failed'
        );
      }

      optionIds.push(id);
    }
  }

  return {
    definitionId: definition.id,
    definitionName: definition.name,
    level,
    width,
    height,
    durability: Number(definition.durability),
    optionIds,
    seed,
  };
}

/**
 * The character whose bag takes a delivery and whose jewels pay for it - the
 * same character for both on purpose, because the fit treats the bag jewels
 * about to be spent as free squares, and that only holds when the spend and
 * the delivery are one bag.
 *
 * ARCHITECTURE.md says "the selected character's inventory", and OpenMU has
 * no such thing to read: `Character` (`DataModel/Entities/Character.cs`)
 * carries `CharacterSlot` and `CreateDate` but no last-played time, `Account`
 * names no current character, and which character a player is on lives in
 * the game server's memory. So the rule is the lowest `CharacterSlot` - the
 * first on the select screen, which the player made first and sees first.
 * `Fulfilment.wallet` counts the same character's bag plus the vault, so the
 * balance the window shows is the balance delivery will spend from. Whatever
 * lands there can be moved through the vault to any other character.
 */
async function deliveryCharacter(
  sql: Sql | TransactionSql,
  resolved: Resolved,
  accountId: string
): Promise<CharacterRow | null> {
  const { character: c } = resolved.schema;
  const rows = await sql.unsafe<CharacterRow[]>(
    `SELECT ${c.col.id} AS id, ${c.col.name} AS name, ${c.col.inventory} AS "inventoryId",
            ${c.col.slot} AS slot, ${c.col.inventoryExtensions} AS "inventoryExtensions"
       FROM ${c.ref}
      WHERE ${c.col.account} = $1 AND ${c.col.inventory} IS NOT NULL
      ORDER BY ${c.col.slot} ASC, ${c.col.id} ASC
      LIMIT 1`,
    [accountId]
  );

  if (!rows[0]) return null;

  return {
    ...rows[0],
    slot: Number(rows[0].slot),
    inventoryExtensions: Number(rows[0].inventoryExtensions),
  };
}

/**
 * Steps 6 to 13. Everything in here runs on the transaction's own connection;
 * a statement on the module-level `sql` would run outside the advisory lock
 * and outside the rollback.
 *
 * The order of the steps is the safety: the wallet is read under lock, the
 * item is resolved and fitted, and only then is anything deleted - so a
 * refusal at any point, including a bag with no room, has cost nothing. The
 * fit treats the bag jewels about to be spent as free squares, since the
 * delete that frees them is in this same transaction; that is what lets a
 * bag full of chaos take the item it is paying for.
 */
async function deliverInTransaction(
  tx: TransactionSql,
  resolved: Resolved,
  account: AccountRow,
  order: Order,
  rehearse: boolean
): Promise<Delivery> {
  const { item: i, itemOptionLink: l, itemDefinition: d } = resolved.schema;

  await tx.unsafe('SELECT pg_advisory_xact_lock(hashtextextended($1::text, 0))', [account.id]);

  const character = await deliveryCharacter(tx, resolved, account.id);

  if (!character) {
    throw new Refusal(
      'You have no character to deliver to. Create one and the order will be delivered.',
      'queued'
    );
  }

  const jewels = await chaosRows(tx, resolved, character.inventoryId, account.vaultId, true);

  if (jewels.length < order.chaos) {
    throw new Refusal(
      `You have ${jewels.length} Jewel${jewels.length === 1 ? '' : 's'} of Chaos ` +
        `and this costs ${order.chaos}. Nothing was spent.`,
      'failed'
    );
  }

  const spent = jewels.slice(0, order.chaos);
  const spentIds = new Set(spent.map(jewel => jewel.id));
  const grant = await resolveGrant(tx, resolved, order);

  const placed = await tx.unsafe<PlacedRow[]>(
    `SELECT i.${i.col.id} AS id, i.${i.col.slot} AS slot,
            d.${d.col.width} AS width, d.${d.col.height} AS height
       FROM ${i.ref} i
       JOIN ${d.ref} d ON d.${d.col.id} = i.${i.col.definition}
      WHERE i.${i.col.storage} = $1 AND i.${i.col.slot} >= $2 AND i.${i.col.slot} < $3`,
    [
      character.inventoryId,
      InventoryConstants.LastEquippableItemSlotIndex + 1,
      InventoryConstants.FirstStoreItemSlotIndex,
    ]
  );
  const occupied: Footprint[] = placed
    .filter(row => !spentIds.has(row.id))
    .map(row => ({
      slot: Number(row.slot),
      width: Number(row.width),
      height: Number(row.height),
    }));
  const rows = gridRows(character.inventoryExtensions);
  const slot = findFreeSlot(occupied, rows, grant.width, grant.height);

  if (slot < 0) {
    // The one refusal that is nobody's fault, and for a gacha the one that
    // must not void a roll committed at placement: it waits for the next
    // logout with room in the bag. A fixed product can simply be bought
    // again, so it fails and gives its daily-cap slot back.
    throw new Refusal(
      `No room in ${character.name}'s bag for a ${grant.width}x${grant.height} item. ` +
        `Make ${grant.width * grant.height} squares free and log out again. Nothing was spent.`,
      order.line === 'gacha' ? 'queued' : 'failed'
    );
  }

  const delivery: Delivery = {
    character: character.name,
    slot,
    spent,
    walletBefore: jewels.length,
    grant,
    itemId: null,
  };

  if (rehearse) throw new Rehearsed(delivery);

  const ids = tx.array(spent.map(jewel => jewel.id));

  // Option rows first, then the items: a jewel has none, but a foreign key is
  // not a thing to find out about mid-transaction.
  await tx.unsafe(`DELETE FROM ${l.ref} WHERE ${l.col.item} = ANY($1::uuid[])`, [ids]);
  const deleted = await tx.unsafe(`DELETE FROM ${i.ref} WHERE ${i.col.id} = ANY($1::uuid[])`, [ids]);

  if (deleted.count !== spent.length) {
    throw new Error(`expected to delete ${spent.length} jewels, deleted ${deleted.count}`);
  }

  const itemColumns = [
    i.col.id,
    i.col.storage,
    i.col.definition,
    i.col.slot,
    i.col.durability,
    i.col.level,
    i.col.hasSkill,
    i.col.socketCount,
    i.col.petExperience,
  ];
  assertInsertable(i, itemColumns);

  const inserted = await tx.unsafe<{ id: string }[]>(
    `INSERT INTO ${i.ref} (${itemColumns.join(', ')})
     VALUES (gen_random_uuid(), $1, $2, $3, $4, $5, false, 0, 0)
     RETURNING ${i.col.id} AS id`,
    [character.inventoryId, grant.definitionId, slot, grant.durability, grant.level]
  );
  const itemId = inserted[0]?.id;

  if (!itemId) throw new Error('the item INSERT returned no id');

  if (grant.optionIds.length > 0) {
    const linkColumns = [l.col.id, l.col.item, l.col.option, l.col.level, l.col.index];
    assertInsertable(l, linkColumns);

    for (const optionId of grant.optionIds) {
      await tx.unsafe(
        `INSERT INTO ${l.ref} (${linkColumns.join(', ')})
         VALUES (gen_random_uuid(), $1, $2, $3, $4)`,
        [itemId, optionId, OPTION_LINK_LEVEL, OPTION_LINK_INDEX]
      );
    }
  }

  return { ...delivery, itemId };
}

