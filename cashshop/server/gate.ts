import net from 'node:net';
import type { Sql } from 'postgres';

/**
 * The safety gate: may the shop write to this account right now?
 *
 * OpenMU holds a logged-in account in a private EF Core context and writes it
 * back on save, so its database is never the live state. Writing to an account
 * the game server has in memory either dupes the jewels the write spends (they
 * were already spent in game, unsaved) or corrupts an inventory slot the player
 * meanwhile filled.
 *
 * Nothing in the database says who is playing - `LoginServer.cs` is a plain
 * in-memory dictionary - so the gate asks four independent questions and lets
 * any one of them refuse. They are chosen to cover each other's blind spots:
 *
 *   presence      sockets, including a player sitting at character select
 *                 (who is never periodically saved). Blind to offline players
 *                 and to anyone bypassing the proxy.
 *   writeRecency  anything in-world, because `PeriodicSaveProgressPlugIn`
 *                 saves every in-world player once a minute. This is what
 *                 catches OpenMU's offline levelling, which has no socket at
 *                 all. Blind to a live account that changes nothing.
 *   personalStore a character parked with a store open - the idle-but-live
 *                 case the other two miss.
 *   portProbe     whether the game port is reachable from outside. Presence is
 *                 only authoritative while the proxy is the only way in, so
 *                 that gets verified rather than assumed.
 *
 * Every signal fails closed. An error, an unreachable service and a missing
 * configuration all read as "refuse", never as "safe". The one reading that
 * looks like an exception - the port probe's timeout - is argued at `tcpProbe`.
 */

export type SignalName = 'presence' | 'writeRecency' | 'personalStore' | 'portProbe';

export interface SignalResult {
  name: SignalName;
  safe: boolean;
  /** Always populated, including when safe, so the audit log records what was seen. */
  reason: string;
  detail?: Record<string, unknown>;
}

export interface GateVerdict {
  account: string;
  safe: boolean;
  /** Why not. Empty when safe. */
  refusals: string[];
  signals: SignalResult[];
  checkedAt: number;
}

export interface GateConfig {
  presenceUrl: string;
  /** How long after the last socket closed before a write is allowed. */
  offlineCooldownMs: number;
  /** `PeriodicSaveProgressPlugIn`'s interval. Its default is one minute. */
  saveIntervalMs: number;
  /** Margin on top of two save intervals before recent writes stop counting. */
  recencyMarginMs: number;
  /** The public address of the game server, as a player's .exe would dial it. */
  gameHost: string | null;
  gamePort: number | null;
  probeTimeoutMs: number;
  probeCacheMs: number;
  requestTimeoutMs: number;
}

export function loadGateConfig(env: Record<string, string | undefined> = process.env): GateConfig {
  const port = Number(env.GAME_PROBE_PORT ?? 0);

  return {
    presenceUrl: env.PRESENCE_URL ?? 'http://127.0.0.1:3001',
    offlineCooldownMs: Number(env.OFFLINE_COOLDOWN_MS ?? 60_000),
    saveIntervalMs: Number(env.SAVE_INTERVAL_MS ?? 60_000),
    recencyMarginMs: Number(env.RECENCY_MARGIN_MS ?? 60_000),
    gameHost: env.GAME_PROBE_HOST ?? null,
    gamePort: port > 0 && port <= 65535 ? port : null,
    probeTimeoutMs: Number(env.GAME_PROBE_TIMEOUT_MS ?? 3_000),
    probeCacheMs: Number(env.GAME_PROBE_CACHE_MS ?? 60_000),
    requestTimeoutMs: Number(env.GATE_REQUEST_TIMEOUT_MS ?? 5_000),
  };
}

