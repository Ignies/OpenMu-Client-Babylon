/**
 * OpenMU's tables are generated by EF Core, so the column names are convention
 * rather than something this repo can read off a model. Two are confirmed
 * (`Item."DefinitionId"` in `Item.Generated.cs`, `Account."VaultId"` by the
 * register service's INSERT); the rest follow the same `<Navigation>Id` rule,
 * and the many-to-many join between an item definition and its option
 * definitions follows EF's `<Owner><Target>` rule, which is why that one
 * carries alternatives.
 *
 * Rather than hardcode the guess, the gate resolves them from
 * `information_schema` on first use and says exactly what is missing when the
 * database disagrees - which is far easier to act on than a syntax error deep
 * inside a query.
 *
 * Every table the shop will ever name is listed here, the fulfilment
 * transaction's included, although the gate itself reads only the first
 * three. One registry and one resolver means `bun run cashshop-gate --schema`
 * shows exactly what the worker will use, and there is no second identifier
 * whitelist to relax by accident.
 */
export interface TableSpec {
  schema: string;
  /** One name, or candidates best first. */
  table: string | string[];
  /** logical name -> the column names that would satisfy it, best first. */
  columns: Record<string, string[]>;
}

